//! PgBouncer configuration rendering for native deployments.
//!
//! PgBouncer is the only database endpoint applications talk to. It listens on
//! a Unix socket inside `/run/doctbase`, never on TCP, and connects to the
//! dedicated PostgreSQL cluster over its local socket. This module owns the
//! rendered `pgbouncer.ini` policy; the install transaction owns file writes,
//! process lifecycle and rollback.
//!
//! Mapping source: `docs/nghien-cuu-cai-dat-cau-hinh.md` (Bước 7) and
//! `specs/001-doctbase-install-config/research.md` §6.

const std = @import("std");

pub const generated_path = "/etc/doctbase/generated/pgbouncer.ini";
pub const unit_name = "doctbase-pgbouncer.service";
pub const unit_template = "deploy/native/units/doctbase-pgbouncer.service.tmpl";
pub const auth_file = "/var/lib/doctbase/pgbouncer/users.txt";
pub const auth_directory = "/var/lib/doctbase/pgbouncer";
pub const auth_user = "pgbouncer_auth";
pub const unix_socket_directory = "/run/doctbase";
pub const unix_socket_group = "doctbase";
pub const listen_port: u16 = 6432;
pub const auth_query = "SELECT * FROM doctbase.pgbouncer_auth($1)";
pub const postgres_socket_directory = "/var/run/postgresql";
pub const postgres_port: u16 = 5433;
pub const file_mode: u16 = 0o640;

pub const Database = struct {
    /// PgBouncer database alias. Projects connect with `doctbase_<slug>_<id>`.
    name: []const u8,
    /// PostgreSQL database name. Defaults to the alias.
    db_name: []const u8 = "",
    host: []const u8 = postgres_socket_directory,
    port: u16 = postgres_port,
    pool_size: u32 = 10,
    max_db_connections: u32 = 20,
};

pub const Options = struct {
    listen_port: u16 = listen_port,
    max_client_conn: u32 = 1000,
    default_pool_size: u32 = 10,
    reserve_pool_size: u32 = 5,
    query_wait_timeout: u32 = 30,
    server_idle_timeout: u32 = 300,
    client_idle_timeout: u32 = 300,
    idle_transaction_timeout: u32 = 60,
    max_prepared_statements: u32 = 200,
    databases: []const Database = &.{},
};

/// Render a complete, socket-only `pgbouncer.ini`.
///
/// Every entry is validated before rendering: aliases are SQL identifiers, the
/// upstream is an absolute Unix socket path, and per-database pool limits are
/// coherent. Wildcard entries are rejected because they would erase the
/// per-project limits the platform promises.
pub fn render(allocator: std.mem.Allocator, options: Options) ![]u8 {
    try validate(options);

    var output = std.Io.Writer.Allocating.init(allocator);
    defer output.deinit();

    try output.writer.writeAll(
        \\# Generated by the Doctbase native installer. DO NOT EDIT.
        \\# Source: instance configuration + control database project registry.
        \\# Apply: sudo doctbase apply
        \\
        \\[databases]
        \\
    );

    for (options.databases) |database| {
        const db_name = if (database.db_name.len == 0) database.name else database.db_name;
        try output.writer.print(
            "{s} = host={s} port={d} dbname={s} pool_size={d} max_db_connections={d}\n",
            .{ database.name, database.host, database.port, db_name, database.pool_size, database.max_db_connections },
        );
    }

    try output.writer.print(
        \\
        \\[pgbouncer]
        \\listen_addr =
        \\unix_socket_dir = {s}
        \\unix_socket_mode = 0660
        \\unix_socket_group = {s}
        \\listen_port = {d}
        \\pool_mode = transaction
        \\max_client_conn = {d}
        \\default_pool_size = {d}
        \\reserve_pool_size = {d}
        \\query_wait_timeout = {d}
        \\server_idle_timeout = {d}
        \\client_idle_timeout = {d}
        \\idle_transaction_timeout = {d}
        \\max_prepared_statements = {d}
        \\auth_type = scram-sha-256
        \\auth_user = {s}
        \\auth_file = {s}
        \\auth_query = {s}
        \\
    , .{
        unix_socket_directory,
        unix_socket_group,
        options.listen_port,
        options.max_client_conn,
        options.default_pool_size,
        options.reserve_pool_size,
        options.query_wait_timeout,
        options.server_idle_timeout,
        options.client_idle_timeout,
        options.idle_transaction_timeout,
        options.max_prepared_statements,
        auth_user,
        auth_file,
        auth_query,
    });

    return try allocator.dupe(u8, output.written());
}

fn validate(options: Options) !void {
    if (options.listen_port == 0) return error.InvalidListenPort;
    if (options.default_pool_size == 0) return error.InvalidPoolSize;
    if (options.max_client_conn == 0) return error.InvalidClientLimit;
    if (options.databases.len == 0) return error.MissingDatabaseEntry;

    for (options.databases, 0..) |database, index| {
        if (!validIdentifier(database.name)) return error.InvalidDatabaseAlias;
        const db_name = if (database.db_name.len == 0) database.name else database.db_name;
        if (!validIdentifier(db_name)) return error.InvalidDatabaseName;
        if (!validUnixSocketPath(database.host)) return error.InvalidUpstreamHost;
        if (database.port == 0) return error.InvalidUpstreamPort;
        if (database.pool_size == 0) return error.InvalidPoolSize;
        if (database.pool_size > database.max_db_connections) return error.PoolExceedsDatabaseLimit;

        for (options.databases[index + 1 ..]) |other| {
            if (std.mem.eql(u8, database.name, other.name)) return error.DuplicateDatabaseAlias;
        }
    }
}

/// PgBouncer database aliases and database names end up in a plain ini file and
/// in SQL identifiers, so keep them to the conservative `[a-z_][a-z0-9_]*`
/// shape used by project provisioning.
pub fn validIdentifier(name: []const u8) bool {
    if (name.len == 0 or name.len > 63) return false;
    for (name, 0..) |byte, index| {
        if (byte == '_') continue;
        if (byte >= 'a' and byte <= 'z') continue;
        if (index != 0 and byte >= '0' and byte <= '9') continue;
        return false;
    }
    return true;
}

/// Native PgBouncer must talk to PostgreSQL over a local socket. An absolute
/// path with no whitespace cannot be confused with a TCP host.
pub fn validUnixSocketPath(path: []const u8) bool {
    if (path.len < 2 or path[0] != '/') return false;
    for (path) |byte| {
        if (byte <= 0x20) return false;
        if (byte == '\'' or byte == '"' or byte == '=') return false;
    }
    return true;
}

/// Render the `auth_file` entry PgBouncer uses to connect for `auth_query`.
/// PgBouncer runs the auth query as `auth_user`, so that account must exist in
/// the userlist even when every other password is resolved from the database.
/// Plain values are quoted and escaped; the file is written `0600` by the
/// caller and never logged.
pub fn renderAuthFile(allocator: std.mem.Allocator, user: []const u8, password: []const u8) ![]u8 {
    if (user.len == 0 or password.len == 0) return error.InvalidSecret;
    if (!validIdentifier(user)) return error.InvalidAuthUser;

    var output = std.Io.Writer.Allocating.init(allocator);
    defer output.deinit();

    try output.writer.writeByte('"');
    for (user) |byte| {
        if (byte == '"' or byte == '\\') try output.writer.writeByte('\\');
        try output.writer.writeByte(byte);
    }
    try output.writer.writeAll("\" \"");
    for (password) |byte| {
        if (byte == '"' or byte == '\\') try output.writer.writeByte('\\');
        try output.writer.writeByte(byte);
    }
    try output.writer.writeAll("\"\n");

    return try allocator.dupe(u8, output.written());
}

comptime {
    if (listen_port == 5432) @compileError("PgBouncer must not reuse the PostgreSQL port");
    if (!validUnixSocketPath(unix_socket_directory)) @compileError("invalid PgBouncer socket directory");
    if (!validUnixSocketPath(auth_file)) @compileError("invalid PgBouncer auth file path");
    if (!validUnixSocketPath(postgres_socket_directory)) @compileError("invalid PostgreSQL socket directory");
    if ((file_mode & 0o007) != 0) @compileError("pgbouncer.ini must not be world accessible");
}
