//! Caddy edge configuration rendering for native deployments.
//!
//! Caddy owns ports 80/443 and TLS. Its admin API is a Unix socket under
//! `/run/doctbase`, never TCP port 2019. This module renders the Caddyfile from
//! the instance configuration plus the project registry; the install/apply
//! transaction validates and reloads it.
//!
//! Mapping sources: `docs/nghien-cuu-cai-dat-cau-hinh.md` (Bước 8, §6.3) and
//! `specs/001-doctbase-install-config/research.md` §7.

const std = @import("std");

pub const generated_path = "/etc/doctbase/generated/Caddyfile";
pub const unit_name = "doctbase-caddy.service";
pub const unit_template = "deploy/native/units/doctbase-caddy.service.tmpl";
pub const admin_socket = "/run/doctbase/caddy-admin.sock";
pub const management_socket = "/run/doctbase/management.sock";
pub const gateway_socket = "/run/doctbase/gateway.sock";
pub const realtime_socket = "/run/doctbase/realtime.sock";
pub const file_mode: u16 = 0o640;

pub const Site = struct {
    /// Public project host, for example `myapp.example.com`.
    host: []const u8,
    upstream_socket: []const u8 = gateway_socket,
    /// Realtime WebSocket traffic is routed directly to the realtime service.
    realtime_socket: ?[]const u8 = realtime_socket,
};

pub const Options = struct {
    /// Empty means local mode: Caddy renders no public site block and the
    /// dashboard is reached through the management socket.
    domain: []const u8 = "",
    acme_email: []const u8 = "",
    admin_socket: []const u8 = admin_socket,
    management_socket: []const u8 = management_socket,
    project_sites: []const Site = &.{},
};

pub fn render(allocator: std.mem.Allocator, options: Options) ![]u8 {
    try validate(options);

    var output = std.Io.Writer.Allocating.init(allocator);
    defer output.deinit();

    try output.writer.writeAll(
        \\# Generated by the Doctbase native installer. DO NOT EDIT.
        \\# Source: instance configuration + control database project registry.
        \\# Apply: sudo doctbase apply
        \\
        \\{
        \\
    );
    try output.writer.print("    admin unix/{s}\n", .{options.admin_socket});
    if (options.acme_email.len != 0) {
        try output.writer.print("    email {s}\n", .{options.acme_email});
    }
    try output.writer.writeAll("}\n");

    if (options.domain.len == 0) {
        try output.writer.writeAll(
            \\
            \\# Local mode: no domain is configured, so Caddy serves no public site.
            \\# Reach the management socket through an SSH tunnel or use `doctbase dev`.
            \\
        );
    } else {
        try output.writer.print("\nadmin.{s} {{\n", .{options.domain});
        try output.writer.writeAll(
            \\    encode zstd gzip
            \\    header {
            \\        Strict-Transport-Security "max-age=31536000; includeSubDomains"
            \\        X-Content-Type-Options "nosniff"
            \\        X-Frame-Options "DENY"
            \\        Referrer-Policy "strict-origin-when-cross-origin"
            \\    }
            \\
        );
        try output.writer.print("    reverse_proxy unix/{s}\n", .{options.management_socket});
        try output.writer.writeAll("}\n");
    }

    for (options.project_sites) |site| {
        try output.writer.print("\n{s} {{\n", .{site.host});
        try output.writer.writeAll("    encode zstd gzip\n");
        if (site.realtime_socket) |realtime| {
            try output.writer.writeAll(
                \\    @realtime path /realtime/v1/*
                \\
            );
            try output.writer.print("    reverse_proxy @realtime unix/{s}\n", .{realtime});
        }
        try output.writer.print("    reverse_proxy unix/{s}\n", .{site.upstream_socket});
        try output.writer.writeAll("}\n");
    }

    return try allocator.dupe(u8, output.written());
}

fn validate(options: Options) !void {
    if (!validSocketPath(options.admin_socket)) return error.InvalidSocketPath;
    if (!validSocketPath(options.management_socket)) return error.InvalidSocketPath;

    if (options.domain.len != 0) {
        if (!validHost(options.domain)) return error.InvalidDomain;
    }
    if (options.acme_email.len != 0 and !validEmail(options.acme_email)) return error.InvalidEmail;

    for (options.project_sites, 0..) |site, index| {
        if (!validHost(site.host)) return error.InvalidHost;
        if (std.mem.eql(u8, site.host, options.domain)) return error.HostConflictsWithInstance;
        if (options.domain.len != 0) {
            if (std.mem.eql(u8, site.host, options.domain)) return error.HostConflictsWithInstance;
            if (isAdminHost(site.host, options.domain)) return error.HostConflictsWithAdmin;
        }
        if (!validSocketPath(site.upstream_socket)) return error.InvalidSocketPath;
        if (site.realtime_socket) |realtime| {
            if (!validSocketPath(realtime)) return error.InvalidSocketPath;
        }
        for (options.project_sites[index + 1 ..]) |other| {
            if (std.mem.eql(u8, site.host, other.host)) return error.DuplicateHost;
        }
    }
}

fn isAdminHost(host: []const u8, domain: []const u8) bool {
    if (host.len <= 6 or !std.mem.startsWith(u8, host, "admin.")) return false;
    return std.mem.eql(u8, host["admin.".len..], domain);
}

/// Lowercase DNS name without wildcards. This is the same rule project
/// provisioning applies, so a rendered Caddyfile can never be interpreted as a
/// different site or inject a directive.
pub fn validHost(host: []const u8) bool {
    if (host.len == 0 or host.len > 253) return false;

    var label_length: usize = 0;
    var previous: u8 = 0;
    for (host) |byte| {
        if (byte == '.') {
            if (label_length == 0) return false;
            if (previous == '-') return false;
            label_length = 0;
            previous = byte;
            continue;
        }
        if (byte == '-') {
            if (label_length == 0) return false;
        } else if (!(byte >= 'a' and byte <= 'z') and !(byte >= '0' and byte <= '9')) {
            return false;
        }
        label_length += 1;
        if (label_length > 63) return false;
        previous = byte;
    }

    return label_length != 0 and previous != '-';
}

fn validEmail(email: []const u8) bool {
    if (email.len == 0 or email.len > 254) return false;
    const at = std.mem.indexOfScalar(u8, email, '@') orelse return false;
    if (at == 0 or at + 1 == email.len) return false;
    if (std.mem.indexOfScalarPos(u8, email, at + 1, '@') != null) return false;
    for (email) |byte| {
        if (byte <= 0x20 or byte == '"' or byte == '<' or byte == '>' or byte == '{' or byte == '}') return false;
    }
    return true;
}

pub fn validSocketPath(path: []const u8) bool {
    if (path.len < 2 or path[0] != '/') return false;
    if (!std.mem.endsWith(u8, path, ".sock")) return false;
    for (path) |byte| {
        if (byte <= 0x20 or byte == '"' or byte == '{' or byte == '}') return false;
    }
    return true;
}

comptime {
    if (!validSocketPath(admin_socket)) @compileError("invalid Caddy admin socket path");
    if (!validSocketPath(management_socket)) @compileError("invalid management socket path");
    if (!validSocketPath(gateway_socket)) @compileError("invalid gateway socket path");
    if (!validSocketPath(realtime_socket)) @compileError("invalid realtime socket path");
}
