//! Native PostgreSQL cluster provisioning for the installer.
//!
//! Doctbase owns a dedicated PostgreSQL 18 cluster (`doctbase`, port 5433)
//! reached only over the local Unix socket. Nothing here shells out: the module
//! renders the generated configuration, pg_hba and bootstrap SQL, then delegates
//! host mutation to `Executor` so the install transaction (T049) owns rollback.
//!
//! Mapping sources: `docs/nghien-cuu-cai-dat-cau-hinh.md` (Bước 6) and
//! `specs/001-doctbase-install-config/research.md` §6, §10.

const std = @import("std");

pub const version = "18";
pub const cluster_name = "doctbase";
pub const port: u16 = 5433;
pub const socket_directory = "/var/run/postgresql";
pub const config_directory = "/etc/postgresql/18/doctbase";
pub const tuning_path = config_directory ++ "/conf.d/doctbase.conf";
pub const hba_path = config_directory ++ "/pg_hba.conf";
pub const data_directory = "/var/lib/postgresql/18/doctbase";
pub const unit_name = "postgresql@18-doctbase.service";

pub const control_database = "doctbase";
pub const template_database = "template_doctbase";
pub const admin_role = "doctbase_admin";
pub const meta_role = "doctbase_meta";
pub const auth_role = "pgbouncer_auth";

/// Minimum and maximum values keep the auto-tuning policy safe on both a 1 GB
/// development VM and a larger single VPS.
pub const shared_buffers_min_mb: u32 = 128;
pub const shared_buffers_max_mb: u32 = 8192;
pub const effective_cache_min_mb: u32 = 256;
pub const effective_cache_max_mb: u32 = 16384;
pub const maintenance_work_mem_min_mb: u32 = 64;
pub const maintenance_work_mem_max_mb: u32 = 1024;
pub const work_mem_min_mb: u32 = 1;
pub const work_mem_max_mb: u32 = 64;

const mib: u64 = 1024 * 1024;
const file_mode: u16 = 0o644;
const hba_mode: u16 = 0o640;

pub const Tuning = struct {
    shared_buffers_mb: u32,
    effective_cache_size_mb: u32,
    maintenance_work_mem_mb: u32,
    work_mem_mb: u32,
};

/// Deterministic auto-tuning. `work_mem` assumes a small number of concurrent
/// sorts per connection, which matches API/control-plane traffic on a single
/// VPS; the value is intentionally conservative because it is per sort node.
pub fn tune(ram_bytes: u64, max_connections: u32) Tuning {
    const ram_mib: u64 = ram_bytes / mib;
    const connections: u64 = @max(@as(u64, max_connections), 1);
    const per_connection: u64 = @max(@as(u64, 1), ram_mib / (connections * 3));

    return .{
        .shared_buffers_mb = clamp(ram_mib / 4, shared_buffers_min_mb, shared_buffers_max_mb),
        .effective_cache_size_mb = clamp(ram_mib / 2, effective_cache_min_mb, effective_cache_max_mb),
        .maintenance_work_mem_mb = clamp(ram_mib / 16, maintenance_work_mem_min_mb, maintenance_work_mem_max_mb),
        .work_mem_mb = clamp(per_connection, work_mem_min_mb, work_mem_max_mb),
    };
}

fn clamp(value: u64, minimum: u32, maximum: u32) u32 {
    return @intCast(std.math.clamp(value, minimum, maximum));
}

pub const TuningOptions = struct {
    tuning: Tuning,
    max_connections: u32,
};

/// Render the conf.d drop-in from the shipped template. Every `@NAME@`
/// placeholder must be known and present, so a stale host copy of the template
/// fails loudly instead of silently dropping a setting.
pub fn renderTuning(allocator: std.mem.Allocator, template: []const u8, options: TuningOptions) ![]u8 {
    var max_connections_buffer: [16]u8 = undefined;
    const max_connections = try std.fmt.bufPrint(&max_connections_buffer, "{d}", .{options.max_connections});

    var shared_buffers_buffer: [16]u8 = undefined;
    var effective_cache_buffer: [16]u8 = undefined;
    var maintenance_work_buffer: [16]u8 = undefined;
    var work_mem_buffer: [16]u8 = undefined;

    const pairs = [_]Pair{
        .{ .name = "MAX_CONNECTIONS", .value = max_connections },
        .{ .name = "SHARED_BUFFERS", .value = try megabytes(&shared_buffers_buffer, options.tuning.shared_buffers_mb) },
        .{ .name = "EFFECTIVE_CACHE_SIZE", .value = try megabytes(&effective_cache_buffer, options.tuning.effective_cache_size_mb) },
        .{ .name = "MAINTENANCE_WORK_MEM", .value = try megabytes(&maintenance_work_buffer, options.tuning.maintenance_work_mem_mb) },
        .{ .name = "WORK_MEM", .value = try megabytes(&work_mem_buffer, options.tuning.work_mem_mb) },
    };

    return substitute(allocator, template, &pairs);
}

fn megabytes(buffer: *[16]u8, value: u32) ![]const u8 {
    return std.fmt.bufPrint(buffer, "{d}MB", .{value});
}

/// `pg_hba.conf` for a socket-only cluster. There are deliberately no `host`
/// lines, so PostgreSQL cannot accept a TCP connection even if a later drop-in
/// re-enables `listen_addresses`.
pub fn renderPgHba(allocator: std.mem.Allocator) ![]u8 {
    return allocator.dupe(u8,
        \\# Generated by the Doctbase native installer. DO NOT EDIT.
        \\# PostgreSQL is Unix-socket only: there are no `host` lines on purpose.
        \\
        \\local   all           postgres                          peer
        \\local   all           all                               scram-sha-256
        \\local   replication   all                               peer
        \\
    );
}

pub const BootstrapValues = struct {
    admin_password: []const u8,
    pgbouncer_password: []const u8,
};

/// Render the bootstrap SQL from the shipped template. Passwords are escaped as
/// SQL string literals; identifiers are fixed constants validated below, never
/// user input.
pub fn renderBootstrap(
    allocator: std.mem.Allocator,
    template: []const u8,
    values: BootstrapValues,
) ![]u8 {
    if (values.admin_password.len == 0) return error.InvalidSecret;
    if (values.pgbouncer_password.len == 0) return error.InvalidSecret;

    const admin_password = try escapeSqlLiteral(allocator, values.admin_password);
    defer allocator.free(admin_password);
    const pgbouncer_password = try escapeSqlLiteral(allocator, values.pgbouncer_password);
    defer allocator.free(pgbouncer_password);

    const pairs = [_]Pair{
        .{ .name = "ADMIN_PASSWORD", .value = admin_password },
        .{ .name = "PGBOUNCER_PASSWORD", .value = pgbouncer_password },
        .{ .name = "CONTROL_DATABASE", .value = control_database },
        .{ .name = "TEMPLATE_DATABASE", .value = template_database },
    };
    return substitute(allocator, template, &pairs);
}

const Pair = struct { name: []const u8, value: []const u8 };

fn substitute(allocator: std.mem.Allocator, template: []const u8, pairs: []const Pair) ![]u8 {
    var output = std.Io.Writer.Allocating.init(allocator);
    defer output.deinit();

    var index: usize = 0;
    while (index < template.len) {
        if (template[index] != '@') {
            try output.writer.writeByte(template[index]);
            index += 1;
            continue;
        }

        // A lone `@` is literal text (for example `%q%u@%d` in a log prefix).
        const end = std.mem.indexOfScalarPos(u8, template, index + 1, '@') orelse {
            try output.writer.writeByte('@');
            index += 1;
            continue;
        };
        const name = template[index + 1 .. end];
        const value = lookup(pairs, name) orelse return error.UnknownPlaceholder;
        try output.writer.writeAll(value);
        index = end + 1;
    }

    return try allocator.dupe(u8, output.written());
}

fn lookup(pairs: []const Pair, name: []const u8) ?[]const u8 {
    for (pairs) |pair| {
        if (std.mem.eql(u8, pair.name, name)) return pair.value;
    }
    return null;
}

fn escapeSqlLiteral(allocator: std.mem.Allocator, value: []const u8) ![]u8 {
    var output = std.Io.Writer.Allocating.init(allocator);
    defer output.deinit();

    for (value) |byte| {
        if (byte == '\'') try output.writer.writeByte('\'');
        try output.writer.writeByte(byte);
    }

    return try allocator.dupe(u8, output.written());
}

pub const ClusterSpec = struct {
    name: []const u8 = cluster_name,
    version: []const u8 = version,
    port: u16 = port,
    socket_directory: []const u8 = socket_directory,
    data_directory: []const u8 = data_directory,
};

pub const FileSpec = struct {
    path: []const u8,
    contents: []const u8,
    mode: u16,
    owner: []const u8,
    group: []const u8,
};

pub const EnsureOptions = struct {
    ram_bytes: u64,
    max_connections: u32,
    tuning_template: []const u8,
    bootstrap_template: []const u8,
    admin_password: []const u8,
    pgbouncer_password: []const u8,
};

/// The adapter runs as root and MUST:
/// - report an existing cluster without recreating or upgrading it;
/// - create the cluster with `pg_createcluster <version> <name> --port <port>`;
/// - atomically replace generated files with the exact mode/owner/group and
///   record them for rollback;
/// - ensure the cluster is running with the current tuning (restart if the
///   generated configuration changed, so `shared_preload_libraries` applies);
/// - stream SQL to `psql` over stdin or a root-only file, never argv/environment,
///   and fail on the first SQL error;
/// - never log a secret value.
pub const Executor = struct {
    context: ?*anyopaque = null,
    running_as_root: bool = false,
    cluster_exists: *const fn (context: ?*anyopaque, spec: ClusterSpec) anyerror!bool,
    create_cluster: *const fn (context: ?*anyopaque, spec: ClusterSpec) anyerror!void,
    write_file: *const fn (context: ?*anyopaque, file: FileSpec) anyerror!void,
    start_cluster: *const fn (context: ?*anyopaque, spec: ClusterSpec) anyerror!void,
    run_sql: *const fn (context: ?*anyopaque, sql: []const u8) anyerror!void,
};

pub fn ensure(allocator: std.mem.Allocator, executor: Executor, options: EnsureOptions) !void {
    if (!executor.running_as_root) return error.RootPrivilegesRequired;

    const spec = ClusterSpec{};
    if (!try executor.cluster_exists(executor.context, spec)) {
        try executor.create_cluster(executor.context, spec);
    }

    const tuning = tune(options.ram_bytes, options.max_connections);
    const tuning_contents = try renderTuning(allocator, options.tuning_template, .{
        .tuning = tuning,
        .max_connections = options.max_connections,
    });
    defer allocator.free(tuning_contents);
    try executor.write_file(executor.context, .{
        .path = tuning_path,
        .contents = tuning_contents,
        .mode = file_mode,
        .owner = "root",
        .group = "root",
    });

    const hba_contents = try renderPgHba(allocator);
    defer allocator.free(hba_contents);
    try executor.write_file(executor.context, .{
        .path = hba_path,
        .contents = hba_contents,
        .mode = hba_mode,
        .owner = "postgres",
        .group = "postgres",
    });

    try executor.start_cluster(executor.context, spec);

    const bootstrap = try renderBootstrap(allocator, options.bootstrap_template, .{
        .admin_password = options.admin_password,
        .pgbouncer_password = options.pgbouncer_password,
    });
    defer allocator.free(bootstrap);
    try executor.run_sql(executor.context, bootstrap);
}

comptime {
    if (port == 5432) @compileError("the Doctbase cluster must not use PostgreSQL's default port");
    if (std.mem.eql(u8, control_database, template_database)) @compileError("control and template databases must differ");
    if (std.mem.eql(u8, admin_role, auth_role)) @compileError("admin and pgbouncer roles must differ");
    if ((file_mode & 0o022) != 0) @compileError("generated tuning must not be group/world writable");
    if ((hba_mode & 0o007) != 0) @compileError("pg_hba.conf must not be world accessible");
    if (shared_buffers_min_mb > shared_buffers_max_mb) @compileError("invalid shared_buffers bounds");
    if (work_mem_min_mb > work_mem_max_mb) @compileError("invalid work_mem bounds");
}
